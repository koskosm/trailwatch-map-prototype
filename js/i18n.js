window.TWLang = {
  get() {
    try {
      return localStorage.getItem("tw_proto_lang") || "en";
    } catch (e) {
      return "en";
    }
  },
  set(lang) {
    localStorage.setItem("tw_proto_lang", lang);
  },
  t(key, vars) {
    const lang = this.get();
    const pack = TW_I18N[lang] || TW_I18N.en;
    let val = key.split(".").reduce((o, k) => (o == null ? o : o[k]), pack);
    if (val == null) {
      val = key.split(".").reduce((o, k) => (o == null ? o : o[k]), TW_I18N.en);
    }
    if (typeof val !== "string") return key;
    if (vars) {
      Object.keys(vars).forEach((k) => {
        val = val.replace(new RegExp("\\{" + k + "\\}", "g"), vars[k]);
      });
    }
    return val;
  },
};
